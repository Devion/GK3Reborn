    private static readonly string[] ComparedClips = ["PARCH2GEO", "TENIERGEOD", "INTRO"];

    [Fact]
    public void The_game_clips_decode_like_ffmpeg()
    {
        Assert.SkipUnless(FfmpegAvailable(), "ffmpeg not on PATH");
        string clips = ClipDirectory();
        Assert.SkipUnless(Directory.Exists(clips), $"clips not found at {clips}");

        string work = Path.Combine(Path.GetTempPath(), "gk3-aac-tests-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(work);
        try
        {
            foreach (string clip in ComparedClips)
            {
                string mp4 = Path.Combine(clips, clip + ".mp4");
                Assert.SkipUnless(File.Exists(mp4), $"{mp4} not found");

                string adts = Path.Combine(work, clip + ".aac");
                string raw = Path.Combine(work, clip + ".f32");
                RunFfmpeg($"-v error -y -i \"{mp4}\" -vn -c:a copy -f adts \"{adts}\"");

                // Decoding the reference from the ADTS stream (not the MP4) keeps ffmpeg from
                // trimming the priming samples, so both sides see the same frames.
                RunFfmpeg($"-v error -y -i \"{adts}\" -f f32le \"{raw}\"");

                float[] ours = DecodeAdts(File.ReadAllBytes(adts), out int channels);
                byte[] referenceBytes = File.ReadAllBytes(raw);
                float[] reference = new float[referenceBytes.Length / 4];
                Buffer.BlockCopy(referenceBytes, 0, reference, 0, referenceBytes.Length);

                Assert.Equal(2, channels);
                Assert.Equal(reference.Length, ours.Length);

                double maxError = 0;
                double errorPower = 0;
                double signalPower = 0;
                for (int i = 0; i < ours.Length; i++)
                {
                    // ffmpeg's float output is not clamped; ours is, by contract.
                    double r = Math.Clamp(reference[i], -1f, 1f);
                    double e = ours[i] - r;
                    maxError = Math.Max(maxError, Math.Abs(e));
                    errorPower += e * e;
                    signalPower += r * r;
                }

                double snr = 10 * Math.Log10(signalPower / Math.Max(errorPower, 1e-30));
                Assert.True(maxError < 1e-3, $"{clip}: max abs error {maxError:E2}");
                Assert.True(snr > 80, $"{clip}: SNR {snr:F1} dB");
            }
        }
        finally
        {
            Directory.Delete(work, recursive: true);
        }
    }

    [Fact]
    public void Every_game_clip_decodes_without_error()
    {
        Assert.SkipUnless(FfmpegAvailable(), "ffmpeg not on PATH");
        string clips = ClipDirectory();
        Assert.SkipUnless(Directory.Exists(clips), $"clips not found at {clips}");

        string work = Path.Combine(Path.GetTempPath(), "gk3-aac-tests-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(work);
        try
        {
            string[] files = Directory.GetFiles(clips, "*.mp4");
            Assert.NotEmpty(files);
            foreach (string mp4 in files)
            {
                string adts = Path.Combine(work, Path.GetFileNameWithoutExtension(mp4) + ".aac");
                RunFfmpeg($"-v error -y -i \"{mp4}\" -vn -c:a copy -f adts \"{adts}\"");
                float[] pcm = DecodeAdts(File.ReadAllBytes(adts), out _);
                Assert.NotEmpty(pcm);
            }
        }
        finally
        {
            Directory.Delete(work, recursive: true);
        }
    }

    private static string ClipDirectory()
    {
        string repository = Assembly.GetExecutingAssembly()
            .GetCustomAttributes<AssemblyMetadataAttribute>()
            .First(a => a.Key == "RepositoryRoot")
            .Value!;

        return Path.GetFullPath(Path.Combine(repository, "..", "ContentWorkspace", "enhanced", "video"));
    }

    private static bool FfmpegAvailable()
    {
        try
        {
            using Process process = Process.Start(new ProcessStartInfo("ffmpeg", "-version")
            {
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                UseShellExecute = false,
            })!;
            process.WaitForExit();
            return process.ExitCode == 0;
        }
        catch (Exception e) when (e is System.ComponentModel.Win32Exception or InvalidOperationException)
        {
            return false;
        }
    }

    private static void RunFfmpeg(string arguments)
    {
        using Process process = Process.Start(new ProcessStartInfo("ffmpeg", arguments)
        {
            RedirectStandardOutput = true,
            RedirectStandardError = true,
            UseShellExecute = false,
        })!;
        string stderr = process.StandardError.ReadToEnd();
        process.WaitForExit();
        Assert.True(process.ExitCode == 0, $"ffmpeg {arguments}: {stderr}");
    }

    /// <summary>Splits an ADTS stream into access units and decodes them all as float PCM.</summary>
    private static float[] DecodeAdts(byte[] data, out int channels)
    {
        List<float> pcm = [];
        AacDecoder? decoder = null;
        float[] frame = [];
        channels = 0;

        int position = 0;
        while (position + 7 <= data.Length)
        {
            Assert.True(data[position] == 0xFF && (data[position + 1] & 0xF6) == 0xF0, $"ADTS sync lost at {position}");
            bool protectionAbsent = (data[position + 1] & 1) != 0;
            int profile = data[position + 2] >> 6;
            int rateIndex = (data[position + 2] >> 2) & 0xF;
            int channelConfig = ((data[position + 2] & 1) << 2) | (data[position + 3] >> 6);
            int length = ((data[position + 3] & 3) << 11) | (data[position + 4] << 3) | (data[position + 5] >> 5);
            int header = protectionAbsent ? 7 : 9;

            if (decoder is null)
            {
                // Rebuild the AudioSpecificConfig the MP4 would have carried.
                int objectType = profile + 1;
                byte[] config =
                [
                    (byte)((objectType << 3) | (rateIndex >> 1)),
                    (byte)(((rateIndex & 1) << 7) | (channelConfig << 3)),
                ];
                decoder = new AacDecoder(config);
                channels = decoder.Channels;
                frame = new float[1024 * channels];
            }

            decoder.Decode(data.AsSpan(position + header, length - header), frame);
            pcm.AddRange(frame);
            position += length;
        }

        return [.. pcm];
    }

