/// <summary>
/// Tests for the managed AAC-LC decoder.
/// </summary>
/// <remarks>
/// The decoder replaces FFmpeg for the movies' audio, so the bar is not "sounds fine"
/// but "matches FFmpeg". The self-contained tests cover configuration parsing and a
/// few frames of a synthetic tone encoded by ffmpeg's own AAC encoder; the reference
/// comparison against the game's clips runs only where ffmpeg and the clips exist.
/// </remarks>
public sealed class AacDecoderTests
{
    // AudioSpecificConfig: AAC-LC (2), 48 kHz (index 3), stereo (2), 1024-sample frames.
    private static readonly byte[] StereoLc48k = [0x11, 0x90];

    // AAC-LC, 48 kHz, mono.
    private static readonly byte[] MonoLc48k = [0x11, 0x88];

    [Fact]
    public void A_plain_lc_config_parses()
    {
        Assert.True(AacDecoder.TryParseConfig(StereoLc48k, out int rate, out int channels, out int objectType));
        Assert.Equal(48000, rate);
        Assert.Equal(2, channels);
        Assert.Equal(2, objectType);

        AacDecoder decoder = new(StereoLc48k);
        Assert.Equal(48000, decoder.SampleRate);
        Assert.Equal(2, decoder.Channels);
        Assert.Equal(1024, decoder.FrameSamples);
    }

    [Fact]
    public void Explicit_sbr_signalling_falls_back_to_the_core_lc_stream()
    {
        // HE-AAC signalling: object type 5, core 24 kHz (index 6), stereo, extension 48 kHz (index 3),
        // then the real object type (2) and the GASpecificConfig. The core is what we decode.
        byte[] config = [0x2B, 0x11, 0x88, 0x00];
        Assert.True(AacDecoder.TryParseConfig(config, out int rate, out int channels, out int objectType));
        Assert.Equal(24000, rate);
        Assert.Equal(2, channels);
        Assert.Equal(2, objectType);
    }

    [Fact]
    public void Unsupported_configurations_are_refused()
    {
        // 960-sample frames.
        Assert.Throws<NotSupportedException>(() => new AacDecoder([0x11, 0x98]));
        Assert.False(AacDecoder.TryParseConfig([0x11, 0x98], out _, out _, out _));

        // 5.1 channels.
        Assert.Throws<NotSupportedException>(() => new AacDecoder([0x11, 0xB0]));

        // Main profile.
        Assert.Throws<NotSupportedException>(() => new AacDecoder([0x09, 0x90]));

        // Too short to be a config at all.
        Assert.False(AacDecoder.TryParseConfig([0x11], out _, out _, out _));
        Assert.Throws<FormatParseException>(() => new AacDecoder([0x11]));
    }

    [Fact]
    public void A_handmade_empty_sce_decodes_to_silence()
    {
        // SCE, tag 0, global_gain 128, ics_info ONLY_LONG with max_sfb 0, no pulse/TNS/gain
        // control, END, byte-aligned: 32 bits exactly.
        byte[] frame = [0x01, 0x00, 0x00, 0x07];
        AacDecoder decoder = new(MonoLc48k);

        float[] output = new float[1024];
        Assert.Equal(1024, decoder.Decode(frame, output));
        Assert.All(output, v => Assert.Equal(0f, v));

        short[] pcm = new short[1024];
        Assert.Equal(1024, decoder.Decode(frame, pcm));
        Assert.All(pcm, v => Assert.Equal((short)0, v));
    }

    [Fact]
    public void A_truncated_frame_is_a_parse_error()
    {
        AacDecoder decoder = new(MonoLc48k);
        float[] output = new float[1024];
        Assert.Throws<FormatParseException>(() => decoder.Decode([0x01], output));
        Assert.Throws<FormatParseException>(() => decoder.Decode([], output));
    }

    [Fact]
    public void The_output_buffer_must_hold_a_whole_frame()
    {
        AacDecoder decoder = new(StereoLc48k);
        Assert.Throws<ArgumentException>(() => decoder.Decode([0x01, 0x00, 0x00, 0x07], new float[1024]));
    }

    [Fact]
    public void An_encoded_tone_matches_ffmpegs_decode()
    {
        // Four access units of a 440 Hz / 1 kHz stereo tone from ffmpeg's aac encoder,
        // with samples of ffmpeg's decode of the fourth (the first three prime the overlap).
        AacDecoder decoder = new(StereoLc48k);
        float[] output = new float[2048];
        foreach (byte[] frame in new[] { Frame0, Frame1, Frame2, Frame3 })
        {
            Assert.Equal(1024, decoder.Decode(frame, output));
        }

        foreach ((int index, float expected) in Frame3Samples)
        {
            Assert.True(Math.Abs(output[index] - expected) < 1e-5f, $"sample {index}: {output[index]} vs {expected}");
        }

        // The 16-bit path is the float path rounded.
        decoder.Reset();
        short[] pcm = new short[2048];
        foreach (byte[] frame in new[] { Frame0, Frame1, Frame2, Frame3 })
        {
            decoder.Decode(frame, pcm);
        }

        for (int i = 0; i < pcm.Length; i++)
        {
            Assert.Equal((short)Math.Clamp(MathF.Round(output[i] * 32768f), short.MinValue, short.MaxValue), pcm[i]);
        }
    }

    [Fact]
    public void Reset_forgets_the_overlap()
    {
        AacDecoder decoder = new(StereoLc48k);
        float[] first = new float[2048];
        decoder.Decode(Frame0, first);

        decoder.Decode(Frame1, new float[2048]);
        decoder.Reset();

        float[] again = new float[2048];
        decoder.Decode(Frame0, again);
        Assert.Equal(first, again);
    }

